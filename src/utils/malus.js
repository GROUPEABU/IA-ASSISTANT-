export function getMalus(co2, prixTTC = null) {
  const row = TABLE_2025.find(([min, max]) => co2 >= min && co2 <= max)
  const malus = row ? row[2] : 0
  if (prixTTC) {
    const plafond = Math.round(prixTTC * 0.6)
    return Math.min(malus, plafond)
  }
  return malus
}

export function getMalusColor(co2) {
  if (co2 < 118) return 'success'
  if (co2 < 131) return 'warning'
  if (co2 < 155) return 'orange'
  return 'danger'
}

export function getMalusLabel(co2) {
  if (co2 < 118) return 'Exonéré'
  if (co2 < 131) return 'Faible'
  if (co2 < 155) return 'Modéré'
  if (co2 < 170) return 'Élevé'
  return 'Très élevé'
}
