export function getMalus(co2) {
  const row = TABLE_2026.find(([min, max]) => co2 >= min && co2 <= max)
  return row ? row[2] : 0
}

export function getMalusColor(co2) {
  if (co2 < 108) return 'success'
  if (co2 < 121) return 'warning'
  if (co2 < 156) return 'orange'
  return 'danger'
}

export function getMalusLabel(co2) {
  if (co2 < 108) return 'Exonéré'
  if (co2 < 121) return 'Faible'
  if (co2 < 156) return 'Modéré'
  if (co2 < 171) return 'Élevé'
  return 'Très élevé'
}
